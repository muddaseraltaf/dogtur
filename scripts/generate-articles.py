SLUG_SET = set()
for a in ARTICLES:
    assert a['slug'] not in SLUG_SET, f"duplicate slug {a['slug']}"
    SLUG_SET.add(a['slug'])
    assert a['section'] in SECTION_NAMES, f"bad section {a['section']}"

# sibling slugs must exist (hubs too)
for a in ARTICLES:
    assert a['hub'] in SLUG_SET, f"{a['slug']}: hub {a['hub']} missing"
    for s in a['siblings']:
        assert s in SLUG_SET, f"{a['slug']}: sibling {s} missing"


def frontmatter(a):
    flags = '[' + ', '.join(f'"{f}"' for f in a['flags']) + ']'
    sibs = '[' + ', '.join(f'"{s}"' for s in a['siblings']) + ']'
    ents = '[' + ', '.join(q(e) for e in a['entities']) + ']'
    desc = a.get('description') or DESC[a['type']](a['title'])
    queue = a['queue'] if a['queue'] is not None else 'null'
    orig = a.get('originalElement')
    lines = [
        '---',
        f'title: {q(a["title"])}',
        f'slug: {q(a["slug"])}',
        f'section: {a["section"]}',
        f'sectionName: {q(SECTION_NAMES[a["section"]])}',
        f'type: {a["type"]}',
        f'intent: {q(a["intent"])}',
        f'flags: {flags}',
        'status: planned',
        f'targetQuery: {q(a["targetQuery"])}',
        f'macroContext: {q(a["macro"])}',
        f'hub: {q(a["hub"])}',
        f'siblings: {sibs}',
        f'publishQueue: {queue}',
    ]
    if orig:
        lines.append(f'originalElement: {q(orig)}')
    lines.append(f'entities: {ents}')
    lines.append(f'description: {q(desc)}')
    lines.append('---')
    return '\n'.join(lines)


def main():
    os.makedirs(OUT, exist_ok=True)
    for a in ARTICLES:
        path = os.path.join(OUT, a['slug'] + '.md')
        with open(path, 'w') as f:
            f.write(frontmatter(a) + '\n\n' + a['body'])
    print(f'wrote {len(ARTICLES)} articles to {OUT}')


if __name__ == '__main__':
    main()
