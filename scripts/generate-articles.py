def q(s):
    """YAML double-quote escape."""
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def brief_body(tq, intent, macro, hub, siblings, original, entities, outline=None):
    lines = [BRIEF_NOTICE, '## Brief', '']
    lines.append(f'- **Target query:** {tq}')
    lines.append(f'- **Intent:** {intent}')
    lines.append(f'- **Macro context:** {macro}')
    lines.append('')
    if outline:
        lines.append('## Contextual vector (ordered, question-form headings)')
        lines.append('')
        for level, text, notes in outline:
            lines.append(f'{"#" * level} {text}')
            if notes:
                lines.append(f'*{notes}*')
            lines.append('')
    lines.append('## Entities & attributes')
    lines.append('')
    for e in entities:
        lines.append(f'- {e}')
    lines.append('')
    lines.append('## Internal links (contextual bridges)')
    lines.append('')
    lines.append(f'- Up to hub: `/{hub}/`')
    for s in siblings:
        lines.append(f'- Sibling: `/{s}/`')
    lines.append('')
    lines.append('## Original element (required before publish)')
    lines.append('')
    lines.append(original)
    lines.append('')
    return '\n'.join(lines)


def skeleton_body(tq, intent, macro, hub, siblings, original, entities, outline):
    return (SKELETON_NOTICE + '\n'
            + brief_body(tq, intent, macro, hub, siblings, original, entities, outline)
                    .split(BRIEF_NOTICE, 1)[1])


